  // room.js의 최상위 let/const는 window 프로퍼티가 아니므로(스크립트 렉시컬 바인딩),
  // 언어는 i18n 내부에 보관하고 room.js가 setLang()으로 알려준다.
  let LANG = 'ko';
  const isEN = () => LANG === 'en';
  function autoLang() {
    const l = (navigator.language || 'en').toLowerCase();
    return l.startsWith('ko') ? 'ko' : 'en';     // 한국어 환경이 아니면 영어로 시작
  }

  window.I18N = {
    isEN, trText, autoLang,
    setLang(l) { LANG = (l === 'en') ? 'en' : 'ko'; },
    getLang() { return LANG; },
    onToggle: null,                              // room.js가 주입(저장 + 새로고침)
    apply() { if (isEN()) translateNode(document.body); startObserver(); },
    // ko ↔ en 전환 (영→한은 원문 복원이 필요하므로 새로고침)
    toggle() {
      LANG = isEN() ? 'ko' : 'en';
      if (typeof this.onToggle === 'function') this.onToggle(LANG);
      else location.reload();
    },
    label() { return isEN() ? '🌐 English' : '🌐 한국어'; },
  };
