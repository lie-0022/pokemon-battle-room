  const EN_RULES = [
    [/자리비운 (\d+)분/g, 'Away $1 min'],
    [/(\d+)일 연속/g, '$1-day streak'],
    [/보유 도구 (\d+) \/ (\d+)/g, 'Gear $1 / $2'],
    [/(\d+)\/(\d+)종/g, '$1/$2 species'],
    [/(\d+)마리/g, '$1'],
    [/(\d+)개/g, '$1'],
    [/(\d+)칸/g, '$1'],
    [/(\d+)위/g, '#$1'],
    [/(\d+)초/g, '$1s'],
  ];

  // ---------- 사전 컴파일 ----------
  let PAIRS = null;
  function buildPairs() {
    const map = Object.assign({}, EN_UI);
    try {
      const P = window.POKEDEX;
      if (P) {
        (P.pokemon || []).forEach((p) => { if (p && p.name && p.en) map[p.name] = enMon(p.en); });
        Object.keys(P.moves || {}).forEach((k) => { const kr = P.moves[k] && P.moves[k].kr; if (kr) map[kr] = TITLE(k); });
        Object.keys(P.typeKr || {}).forEach((t) => { map[P.typeKr[t]] = TITLE(t); });
      }
    } catch (e) { /* 데이터 없으면 UI 사전만 */ }
    // 긴 문장 우선 (짧은 조각이 긴 문장을 깨지 않도록)
    PAIRS = Object.keys(map).filter((k) => k.length).sort((a, b) => b.length - a.length).map((k) => [k, map[k]]);
  }

  function trText(s) {
    if (!PAIRS) buildPairs();
    let out = s;
    for (let i = 0; i < EN_PRE.length; i++) out = out.replace(EN_PRE[i][0], EN_PRE[i][1]);
    for (let i = 0; i < PAIRS.length; i++) {
      const [ko, en] = PAIRS[i];
      if (out.indexOf(ko) !== -1) out = out.split(ko).join(en);
    }
    for (let i = 0; i < EN_RULES.length; i++) out = out.replace(EN_RULES[i][0], EN_RULES[i][1]);
    return out;
  }

  // ---------- DOM 번역 ----------
  const HAS_KO = /[가-힣]/;
  function translateNode(node) {
    if (node.nodeType === 3) {                       // 텍스트 노드
      if (HAS_KO.test(node.nodeValue)) { const t = trText(node.nodeValue); if (t !== node.nodeValue) node.nodeValue = t; }
      return;
    }
    if (node.nodeType !== 1) return;
    if (node.tagName === 'SCRIPT' || node.tagName === 'STYLE') return;
    for (const a of ['title', 'placeholder', 'alt']) {
      const v = node.getAttribute && node.getAttribute(a);
      if (v && HAS_KO.test(v)) node.setAttribute(a, trText(v));
    }
    for (let c = node.firstChild; c; c = c.nextSibling) translateNode(c);
  }

  let observer = null;
  function startObserver() {
    if (observer) return;
    observer = new MutationObserver((muts) => {
      if (!isEN()) return;
      for (const m of muts) {
        if (m.type === 'characterData') { if (HAS_KO.test(m.target.nodeValue)) translateNode(m.target); }
        else m.addedNodes.forEach(translateNode);
      }
    });
    observer.observe(document.body, { childList: true, subtree: true, characterData: true });
  }

